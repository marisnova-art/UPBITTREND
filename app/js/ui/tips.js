const SEL = '[data-tip], .badge, .pill, dt, th, h3, h2, .legend span, .lbl-toggle, .guide-row > span:nth-child(2), .kv2 td:first-child, .surge-stats summary, #sbAssets, #sbPnl';
const ownText = el => { let t = ''; for (const n of el.childNodes) if (n.nodeType === 3) t += n.textContent; return t.trim(); };

export function initTips(){
  const box = document.createElement('div'); box.className = 'qtip'; box.setAttribute('role', 'tooltip'); document.body.appendChild(box);
  let cur = null, timer = null;
  const hide = () => { clearTimeout(timer); cur = null; box.classList.remove('on'); };
  const textFor = el => {
    if (el.dataset.tip) return el.dataset.tip;
    const own = ownText(el), full = el.textContent.trim();
    return TIPS[own] || TIPS[full] || TIPS[full.replace(/\s*\d+$/, '')] || null;
  };
  document.addEventListener('mouseover', e => {
    if (matchMedia('(hover: none)').matches) return;
    let el = e.target.closest(SEL), txt = null;
    while (el && !(txt = textFor(el))) el = el.parentElement && el.parentElement.closest(SEL);
    if (!el){ if (cur) hide(); return; }
    if (el === cur) return;
    hide(); cur = el;
    timer = setTimeout(() => {
      box.textContent = txt; box.classList.add('on');
      const r = el.getBoundingClientRect(), b = box.getBoundingClientRect();
      let x = r.left + r.width / 2 - b.width / 2, y = r.bottom + 6;
      if (y + b.height > innerHeight - 4) y = r.top - b.height - 6;
      x = Math.max(6, Math.min(innerWidth - b.width - 6, x));
      box.style.left = x + 'px'; box.style.top = y + 'px';
    }, 350);
  });
  document.addEventListener('mousedown', hide);
  addEventListener('scroll', hide, true);
}
